def ping_redis():
    try:
        r = redis.Redis.from_url(REDIS_URL, socket_connect_timeout=3)
        r.ping()
        print("Redis PING ok")
    except redis.RedisError:
        print("Redis PING failed")

def ping_db() -> bool:
    try:
        with psycopg.connect(DATABASE_URL , connect_timeout=3) as conn:

            with conn.cursor() as cur:
                cur.execute("SELECT 1")
                return cur.fetchone() is not None
    except:
        return False



@app.get("/" , summary="API info" , description="Returns the name, version and main endpoints of this API.")
async def root():
    return { "name": "Task API", "version": "1.0", "endpoints": ["/tasks"] }

@app.get("/health" , summary="Health check" , description="Returns status ok if the server is alive.")
def health():
    if ping_db():
        return {"status": "ok", "db": "ok"}

    return JSONResponse(status_code=503, content={"status": "error", "db": "error"})
         

@app.get("/tasks" , summary="List all tasks" , description="Returns every task in the in-memory list.")
def get_tasks(db:psycopg.Connection = Depends(get_db)):
    cursor = db.cursor()
    cursor.execute("SELECT * from tasks")

    rows = cursor.fetchall()
    return rows


@app.get("/tasks/{id}" , summary="Get one task" , description="Return one task with the given id")
def get_task_by_id(id:int , db:psycopg.Connection = Depends(get_db)):
    cursor = db.cursor()
    cursor.execute("SELECT * from tasks where id = %s" , (id,))

    row = cursor.fetchone()
    if row:
        return row
    raise HTTPException(
        status_code=404,
        detail={ "error": f"Task {id} not found" }
    )

@app.post("/tasks" , status_code=201 , summary="create a task" , description="Creates a tasks with a title")
def create_task(title:str = Body(default=None, embed=True) , db:psycopg.Connection=Depends(get_db)):
    cursor = db.cursor()
    if not title or title.strip()=="":
        raise HTTPException(
            status_code=400,
            detail={"error":"what's wrong"}
        )
    
    cursor.execute("INSERT INTO tasks (title) VALUES (%s)",(title,))
    db.commit()
    cursor.execute("SELECT * from tasks where title = %s" , (title,))
    data = cursor.fetchone()
    return data

@app.put("/tasks/{id}" , summary="Update a task" , description="Changes the title and/or the done status of the task")
def update_task(id:int , update_data : task_val , db:psycopg.Connection = Depends(get_db)):
    data = update_data.model_dump(exclude_unset=True)
    if not data:
         raise HTTPException(status_code=400, detail="Empty request body. Provide at least one field to update.")
    with db.cursor() as cursor:
        cursor.execute("SELECT 1 FROM tasks where id = %s", (id,))
        task = cursor.fetchone()
        if task is None:
            raise HTTPException(
                status_code=404,
                detail="Unknown ID"
            )
        fields = ", ".join(f"{key} = %s" for key in data)
        values = list(data.values())
        values.append(id)
        cursor.execute(f"UPDATE tasks SET {fields} WHERE id = %s RETURNING *", values)

        db.commit()

        updated_task = cursor.fetchone()
        return updated_task

@app.delete("/tasks/{id}" , status_code=204, summary="Delete a task" , description="Removes the task with the given ID")
def delete_task(id:int , db:psycopg.Connection = Depends(get_db)):
    cursor = db.cursor()
    cursor.execute("SELECT 1 FROM tasks where id = %s", (id,))
    task = cursor.fetchone()
    if task is None:
        raise HTTPException(
            status_code=404,
            detail="Unknown ID"
        )
    cursor.execute("DELETE FROM tasks WHERE id = %s" , (id,))
    db.commit()
    return 


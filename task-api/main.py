from fastapi import FastAPI , HTTPException , Body , Response , Depends , status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from pydantic import BaseModel, field_validator
import sqlite3
import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv
import os
import redis
from contextlib import asynccontextmanager

@asynccontextmanager
async def lifespan(app: FastAPI):
    init_db()
    ping_redis()
    yield

app = FastAPI(title="Task API" , version="1.0" , lifespan=lifespan)
load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")
REDIS_URL = os.getenv("REDIS_URL")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],           
    allow_credentials=True,         
    allow_methods=["*"],             
    allow_headers=["*"],             
)

class task_val(BaseModel):
    title : str | None = None
    done : bool | None = None 

def get_db():
    """Connect to database"""
    conn = psycopg.connect(DATABASE_URL , row_factory=dict_row , connect_timeout=5)

    try:
        yield conn
    finally:
        conn.close()

def init_db():
    with psycopg.connect(DATABASE_URL) as conn:
        cursor = conn.cursor()
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS tasks (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT,
            done BOOLEAN NOT NULL DEFAULT FALSE
        );
        """)

        cursor.execute("select COUNT(*) from tasks")
        row_count = cursor.fetchone()[0]
        if row_count==0:
            example_tasks = [
                ("Buy milk" , False),
                ("Water the plants" , True),
                ("Backup files" , False)
            ]
            cursor.executemany("INSERT INTO tasks(title , done) VALUES (%s,%s)",example_tasks)
            conn.commit()
            print("Database seeded with 3 example")
        else:
            print("Table already has data. Skiping seeding.")
